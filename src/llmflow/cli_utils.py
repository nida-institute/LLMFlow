def _register_in_global_registry(base_dir: Path) -> None:
    """Register the project and its ai-context files in ~/.sp/ (Issue #132).

    Idempotent — skips entries that are already registered.
    """
    import re

    try:
        from llmflow.registry import Registry

        registry_dir = Path.home() / ".sp"
        registry = Registry(registry_dir)

        project_name = base_dir.name
        project_path = str(base_dir.resolve())

        # Register the project
        if registry.projects.get(project_name) is None:
            registry.projects.register(name=project_name, path=project_path)
            logger.info(f"Registered project '{project_name}' in ~/.sp/projects/")
        else:
            logger.info(f"Project '{project_name}' already registered in ~/.sp/")

        # Index docs/ai-context/*.md files
        ai_context_dir = base_dir / "docs" / "ai-context"
        if ai_context_dir.exists():
            for md_file in sorted(ai_context_dir.glob("*.md")):
                file_key = md_file.name
                if registry.ai_context.get(file_key) is not None:
                    continue  # already indexed

                # Extract description from first ATX heading in the file
                description = f"AI context: {md_file.stem}"
                try:
                    content = md_file.read_text(encoding="utf-8")
                    for line in content.splitlines():
                        stripped = line.strip()
                        if stripped.startswith("#"):
                            description = re.sub(r"^#+\s*", "", stripped)
                            break
                except OSError:
                    pass

                # Derive topics from filename parts
                topics = [p for p in re.split(r"[-_.]", md_file.stem) if p]
                topics.append("ai-context")

                registry.ai_context.register(
                    file=file_key,
                    project=project_name,
                    description=description,
                    topics=topics,
                    path=str(md_file.resolve()),
                )
                logger.info(f"Indexed {file_key} in ~/.sp/ai-context/")

    except Exception as e:
        logger.warning(f"Could not register in global registry: {e}")
        logger.warning("This is not critical - registry can be updated manually.")


def list_pipelines(directory: str) -> list[str]:
    """List all YAML pipeline files in a directory."""
    base = Path(directory)
    if not base.exists():
        return []
    pipelines: list[str] = []
    for pattern in ("*.yaml", "*.yml"):
        for path in base.rglob(pattern):
            if path.is_file():
                pipelines.append(str(path.relative_to(base)))
    return sorted(dict.fromkeys(pipelines))


def sync_ai_context_files(base_dir: Path) -> None:
    """Copy ai-context files from the installed LLMFlow package to the consumer repo.

    Files are copied to .github/ai-context/ in the consumer repo.
    This allows consumer repos to reference the canonical AI context files
    without manually copying them or keeping them in sync.
    """
    import importlib.resources
    import shutil

    # Target directory in consumer repo
    target_dir = base_dir / ".github" / "ai-context"
    target_dir.mkdir(parents=True, exist_ok=True)

    # Python 3.9+ uses importlib.resources.files()
    try:
        # Try Python 3.9+ API - docs are packaged under llmflow/docs/
        docs_root = importlib.resources.files("llmflow").joinpath("docs")

        # Copy ai-context files
        ai_context_source = docs_root.joinpath("ai-context")
        if ai_context_source.is_dir():
            for item in ai_context_source.iterdir():
                if item.is_file() and Path(str(item)).suffix == ".md":
                    target_file = target_dir / item.name
                    # Read and write to handle package resources properly
                    content = item.read_text(encoding="utf-8")
                    target_file.write_text(content, encoding="utf-8")
                    logger.info(f"Synced .github/ai-context/{item.name}")

        # Copy audits/ directory files
        audits_source = docs_root.joinpath("audits")
        audits_target = base_dir / ".github" / "ai-context" / "audits"
        audits_target.mkdir(parents=True, exist_ok=True)

        if audits_source.is_dir():
            for item in audits_source.iterdir():
                if item.is_file() and Path(str(item)).suffix == ".md":
                    target_file = audits_target / item.name
                    content = item.read_text(encoding="utf-8")
                    target_file.write_text(content, encoding="utf-8")
                    logger.info(f"Synced .github/ai-context/audits/{item.name}")

    except (AttributeError, TypeError):
        # Fallback for older Python or if files() doesn't work
        logger.warning("Could not sync ai-context files from installed package.")
        logger.warning("This feature requires Python 3.9+ or a properly installed LLMFlow package.")
    except Exception as e:
        logger.error(f"Error syncing ai-context files: {e}")

    logger.info("AI context sync complete. Files copied to .github/ai-context/")