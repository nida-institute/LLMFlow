#!/usr/bin/env python3
"""Report the shared set against Human at the Helm, and leave Helm a note of what it owes.

Design: `project/plans/design-helm-coordination.md` (#271). The record is
`data/helm-sync.yaml`; its tests are `tests/test_helm_sync.py`; this script's are
`tests/test_sync_helm_tool.py`.

**A shared file changes in one repository per act.** A change here is committed here and
recorded as `pending`; Helm adopts it in its own commit. This script never writes Helm's
shared files. The one place it writes in Helm's tree is `collab/scripture-pipelines/`, and only
when asked — the project rule "Human at the Helm is written in Helm".

    hatch run python tools/sync_helm.py                   # report; writes nothing
    hatch run python tools/sync_helm.py --refresh-record  # record this repository's changes
    hatch run python tools/sync_helm.py --note            # leave Helm a note per pending file

**Both sides are read at `HEAD`**, not from disk, so two uncommitted trees cannot agree with
each other. A shared path with uncommitted changes is named rather than compared.
`--refresh-record` is the exception: it hashes this repository's working copy, because a change
and its record are committed together.

**Where the shared set comes from.** The classification constants in
`tests/test_portable_skills.py` and `tests/test_portable_disciplines.py` — the same ones the
guards enforce. Importing them from the tests is deliberate: a copy of "which skills are
shared" living here as well is precisely the second hand-kept list that left three
disciplines unshipped for months (#204).
"""

from __future__ import annotations

import argparse
import datetime
import difflib
import hashlib
import subprocess
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from tests.test_helm_sync import (  # noqa: E402
    DEFAULT_HELM_CLONE,
    HELM_ENV_VAR,
    RECORD_PATH,
    _derived_shared_set,
    _helm_root,
    _source_path,
    _target_path,
)
from tests.test_portable_skills import ENGINE_VOCABULARY, _offenders  # noqa: E402

#: Where a note to Helm goes — the one directory in Helm's tree a session here may write.
NOTE_DIR = Path("collab") / "scripture-pipelines"

#: A `pending` entry's own fields. They go when Helm adopts the change.
PENDING_FIELDS = ("owner", "since", "note")

# The script owns this header and rewrites it with the file. Anything a human needs to say
# about a particular file goes in that entry's `ruling` or `note` field, which is data and
# survives a regeneration — a comment beside an entry would not.
HEADER = """\
# The state of the set shared with Human at the Helm (#271, design-helm-coordination.md).
#
# GENERATED BY tools/sync_helm.py. Hashes and statuses are rewritten by that script; the
# `ruling`, `note` and `helm_only` texts are written by hand and preserved across regenerations.
#
# Ruling H3-B: LLMFlow is upstream, and the two sides may only differ where a ruling says
# so. A shared file changes in one repository per act: a change here is recorded `pending`,
# and Helm adopts it in its own commit. `tests/test_helm_sync.py` checks this file against
# what the package ships and nothing about Helm — Helm being behind turns Helm red, not this
# repository (`failure-lands-where-the-fix-belongs`).
#
# ---------------------------------------------------------------------------
# Fields
#
#   set      skills | disciplines | root   (which shipped directory the file comes from)
#   name     file or skill directory name
#   sha256   hash of THIS repository's copy, at the last refresh
#   status   identical  the two copies must match byte for byte
#            differs    they are allowed to differ, and `ruling` says why
#            pending    changed here, not yet adopted by Helm
#   ruling   the decision permitting a difference. Required when status is `differs`;
#            quote the Captain rather than paraphrasing.
#   owner    whose move a `pending` change waits on — always `helm`
#   since    the date the change was recorded here
#   note     what changed and why Helm should adopt it; travels to Helm with `--note`
#
# `helm_only` lists what Human at the Helm ships that this repository does not share — its
# own skills, its forks, and the essays its README calls the disciplines proper. Each entry
# carries a `path` and a `note` saying what it is.
# ---------------------------------------------------------------------------
"""


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _key(entry: dict) -> str:
    return f"{entry['set']}/{entry['name']}"


# ---------------------------------------------------------------------------
# Committed state
# ---------------------------------------------------------------------------


def _git(repo: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", "-C", str(repo), *args], capture_output=True, check=False)


def committed_text(repo: Path, relpath: str) -> bytes | None:
    """The file as committed at `HEAD`, or None if it has never been committed."""
    shown = _git(repo, "show", f"HEAD:{relpath}")
    return shown.stdout if shown.returncode == 0 else None


def committed_sha256(repo: Path, relpath: str) -> str | None:
    blob = committed_text(repo, relpath)
    return None if blob is None else hashlib.sha256(blob).hexdigest()


def is_dirty(repo: Path, relpath: str) -> bool:
    """True when the path differs from `HEAD` in the working tree or the index."""
    return bool(_git(repo, "status", "--porcelain", "--", relpath).stdout.strip())


def _relative(entry: dict, helm: Path) -> str:
    return _target_path(entry, helm).relative_to(helm).as_posix()


def _ours_relative(entry: dict) -> str:
    return _source_path(entry).relative_to(REPO_ROOT).as_posix()


# ---------------------------------------------------------------------------
# The record
# ---------------------------------------------------------------------------


def refreshed(
    prior: dict | None,
    sha: str,
    today: str,
    *,
    key: str | None = None,
    helm_sha: str | None = None,
) -> dict:
    """The entry after this repository's copy hashes to `sha`.

    A changed `identical` file becomes `pending` on Helm, with an empty `note` that the record
    test refuses until somebody says why. A ruled file keeps its ruling. A `pending` file Helm
    has committed identically — `helm_sha` — is adopted, and becomes `identical` again.
    """
    if prior is None:
        set_id, name = (key or "").split("/", 1)
        return {"set": set_id, "name": name, "sha256": sha, "status": "pending",
                "owner": "helm", "since": today, "note": ""}

    entry = dict(prior)
    changed = entry["sha256"] != sha
    entry["sha256"] = sha

    if entry["status"] == "pending" and helm_sha == sha:
        for field in PENDING_FIELDS:
            entry.pop(field, None)
        entry["status"] = "identical"
    elif changed and entry["status"] == "identical":
        entry.update(status="pending", owner="helm", since=today, note="")
    return entry


def _load_existing() -> dict:
    if not RECORD_PATH.is_file():
        return {}
    return yaml.safe_load(RECORD_PATH.read_text(encoding="utf-8")) or {}


def _build(existing: dict, today: str, helm: Path | None) -> list[dict]:
    """One entry per shared file, from this repository's working copy."""
    prior = {_key(e): e for e in (existing.get("files") or ())}
    entries = []
    for key in sorted(_derived_shared_set()):
        set_id, name = key.split("/", 1)
        stub = {"set": set_id, "name": name}
        helm_sha = committed_sha256(helm, _relative(stub, helm)) if helm else None
        entries.append(
            refreshed(prior.get(key), _sha256(_source_path(stub)), today, key=key,
                      helm_sha=helm_sha)
        )
    return entries


def _write_record(existing: dict, entries: list[dict]) -> None:
    body = {
        "version": 1,
        "helm_clone_default": existing.get("helm_clone_default", DEFAULT_HELM_CLONE),
        "files": entries,
        "helm_only": existing.get("helm_only") or [],
    }
    RECORD_PATH.write_text(
        # allow_unicode: the rulings quote the Captain, and an em dash escaped to —
        # makes a hand-written sentence unreadable in the file it was written into.
        HEADER
        + "\n"
        + yaml.safe_dump(body, sort_keys=False, width=96, allow_unicode=True),
        encoding="utf-8",
    )


# ---------------------------------------------------------------------------
# The report
# ---------------------------------------------------------------------------


def verdict(entry: dict, ours: str | None, helm: Path) -> str:
    """What Helm's committed copy says about one entry. Never a failure in this repository."""
    relpath = _relative(entry, helm)
    if is_dirty(helm, relpath):
        return "uncommitted in Helm"
    theirs = committed_sha256(helm, relpath)
    if theirs is None:
        return "MISSING"
    status = entry["status"]
    if status == "pending":
        return "adopted" if theirs == ours else "pending"
    if status == "differs":
        if theirs == ours:
            return "RULING OVERTAKEN"
        text = (committed_text(helm, relpath) or b"").decode("utf-8")
        return "ENGINE VOCABULARY" if _offenders(text, ENGINE_VOCABULARY) else "ruled"
    return "same" if theirs == ours else "HELM DIVERGED"


def _unexplained(helm: Path, entries: list[dict], existing: dict) -> list[str]:
    """What Helm ships that the record neither shares nor lists as Helm's own."""
    present = {
        f"skills/{p.name}" for p in (helm / "skills").iterdir() if (p / "SKILL.md").is_file()
    } if (helm / "skills").is_dir() else set()
    if (helm / "disciplines").is_dir():
        present |= {f"disciplines/{p.name}" for p in (helm / "disciplines").glob("*.md")}
    accounted = {_key(e) for e in entries} | {
        e["path"] for e in (existing.get("helm_only") or ())
    }
    return sorted(present - accounted)


#: What each verdict means, printed once under the table.
LEGEND = {
    "pending": "changed here, not yet adopted — Helm's move; `--note` leaves it the text",
    "adopted": "Helm has adopted a pending change — run --refresh-record to mark it identical",
    "HELM DIVERGED": "Helm changed a shared file with no ruling — Helm's to revert (D-C)",
    "RULING OVERTAKEN": "the copies now match — drop the ruling and record it identical",
    "ENGINE VOCABULARY": "Helm's ruled copy names this engine — Helm's to remove",
    "MISSING": "recorded as shared, absent from Helm's committed tree",
    "uncommitted in Helm": "Helm's copy has uncommitted changes — not compared",
}


#: The verdict column, wide enough for the longest verdict.
WIDTH = max(len(v) for v in (*LEGEND, "uncommitted here", "UNEXPLAINED"))


def _report(entries: list[dict], helm: Path | None, existing: dict) -> None:
    print(f"Shared with Human at the Helm: {len(entries)} files")
    print(f"  from  {_source_path(entries[0]).parent.parent}")
    print(f"  to    {helm if helm else '(no clone found)'}\n")

    seen: set[str] = set()
    for entry in entries:
        key = _key(entry)
        ours_rel = _ours_relative(entry)
        if is_dirty(REPO_ROOT, ours_rel):
            print(f"  {'uncommitted here':{WIDTH}}  {key}")
            continue
        ours = committed_sha256(REPO_ROOT, ours_rel)
        if helm is None:
            print(f"  {entry['status']:{WIDTH}}  {key}")
            continue
        found = verdict(entry, ours, helm)
        seen.add(found)
        detail = f"  (since {entry['since']})" if found == "pending" else ""
        print(f"  {found:{WIDTH}}  {key}{detail}")

    if helm is not None:
        for path in _unexplained(helm, entries, existing):
            seen.add("UNEXPLAINED")
            print(f"  {'UNEXPLAINED':{WIDTH}}  {path}  (in Helm; neither shared nor helm_only)")

    legend = [(v, LEGEND[v]) for v in LEGEND if v in seen]
    if legend:
        print()
        for name, meaning in legend:
            print(f"  {name}: {meaning}")
    print("\nNothing about Helm fails this repository's suite; Helm's own check is where it turns red.")


# ---------------------------------------------------------------------------
# Notes to Helm
# ---------------------------------------------------------------------------


def write_notes(pending: list[tuple[dict, str]], helm: Path, today: str) -> list[Path]:
    """One note per `pending` entry, in Helm's `collab/scripture-pipelines/`, and nothing else.

    `pending` pairs each entry with this repository's committed text of it. Helm's session reads
    the note, adopts the change in Helm's words, and commits it there.
    """
    written = []
    for entry, ours in pending:
        if entry["status"] != "pending":
            continue
        relpath = _relative(entry, helm)
        theirs = (committed_text(helm, relpath) or b"").decode("utf-8")
        diff = "".join(
            difflib.unified_diff(
                theirs.splitlines(keepends=True),
                ours.splitlines(keepends=True),
                fromfile=f"helm/{relpath}",
                tofile=f"scripture-pipelines/{relpath}",
            )
        )
        slug = f"{entry['set']}-{Path(entry['name']).stem}"
        note = helm / NOTE_DIR / f"{today}-adopt-{slug}.md"
        note.parent.mkdir(parents=True, exist_ok=True)
        note.write_text(
            f"# Adopt a change to `{_key(entry)}` from Scripture Pipelines\n\n"
            f"**Pending since {entry['since']}.** Written by `tools/sync_helm.py --note` into the\n"
            "one directory a Scripture Pipelines session may write here. Adopt it in Helm's own\n"
            "commit — in Helm's words where they differ — or record why not.\n\n"
            f"## Why\n\n{entry['note'].strip()}\n\n"
            f"## The change, against Helm's committed `{relpath}`\n\n"
            f"```diff\n{diff}```\n\n"
            f"## Scripture Pipelines' text\n\n````markdown\n{ours}````\n",
            encoding="utf-8",
        )
        written.append(note)
    return written


# ---------------------------------------------------------------------------
# Command line
# ---------------------------------------------------------------------------


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--refresh-record",
        action="store_true",
        help="record this repository's changes: a changed shared file becomes pending on Helm",
    )
    parser.add_argument(
        "--note",
        action="store_true",
        help="write a note per pending file into Helm's collab/scripture-pipelines/",
    )
    args = parser.parse_args(argv)

    existing = _load_existing()
    helm = _helm_root()
    today = datetime.date.today().isoformat()

    if args.refresh_record:
        _write_record(existing, _build(existing, today, helm))
        print(f"Record refreshed: {RECORD_PATH.relative_to(REPO_ROOT)}")
        existing = _load_existing()

    entries = existing.get("files") or []

    if args.note:
        if helm is None:
            print(
                f"No Human at the Helm clone found. Set ${HELM_ENV_VAR}, or clone it to "
                f"{existing.get('helm_clone_default', DEFAULT_HELM_CLONE)}.",
                file=sys.stderr,
            )
            return 2
        pending = [
            (e, (committed_text(REPO_ROOT, _ours_relative(e)) or b"").decode("utf-8"))
            for e in entries
        ]
        for path in write_notes(pending, helm, today):
            print(f"  note       {path}")
        return 0

    _report(entries, helm, existing)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
